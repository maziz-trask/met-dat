-- MET-DAT schema. See docs/database-design.md

CREATE TABLE test_type (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(150) NOT NULL,
    description  VARCHAR(1000),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    modified_by  VARCHAR(255),
    modified_at  TIMESTAMPTZ
);
CREATE UNIQUE INDEX ux_test_type_name ON test_type (lower(name));

CREATE TABLE app_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    role        VARCHAR(10)  NOT NULL,
    department  VARCHAR(20),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_app_user_role CHECK (role IN ('READER', 'EDITOR'))
);
CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email));

CREATE SEQUENCE test_number_seq START WITH 51 INCREMENT BY 1;

CREATE TABLE technical_test (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_number        VARCHAR(20)  NOT NULL,              -- business ID, e.g. TEST-2026-0001
    vin                VARCHAR(17)  NOT NULL,
    test_type_id       BIGINT       NOT NULL REFERENCES test_type (id),  -- never deleted, only deactivated
    department         VARCHAR(20)  NOT NULL,
    test_year          INTEGER     NOT NULL,              -- ISO week-based year
    test_week          INTEGER     NOT NULL,              -- ISO calendar week 1..53
    test_date          DATE,                               -- exact date, only when the user supplied one
    period_start       DATE         NOT NULL,              -- Monday of the ISO week (or test_date)
    period_end         DATE         NOT NULL,              -- Sunday of the ISO week (or test_date)
    responsible_person VARCHAR(150) NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    result             VARCHAR(30),
    comment            TEXT,
    created_by         VARCHAR(255) NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    modified_by        VARCHAR(255),
    modified_at        TIMESTAMPTZ,
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ux_technical_test_number UNIQUE (test_number),
    CONSTRAINT ck_test_status CHECK (status IN ('Draft', 'Planned', 'In Progress', 'Completed', 'Cancelled')),
    CONSTRAINT ck_test_result CHECK (result IS NULL OR result IN
        ('Passed', 'Failed', 'Not evaluated', 'Conditionally passed', 'Passed with remarks', 'Preliminary', 'Cancelled')),
    CONSTRAINT ck_test_week   CHECK (test_week BETWEEN 1 AND 53),
    CONSTRAINT ck_test_period CHECK (period_start <= period_end)
);
CREATE INDEX ix_test_vin        ON technical_test (upper(vin));
CREATE INDEX ix_test_type       ON technical_test (test_type_id);
CREATE INDEX ix_test_status     ON technical_test (status);
CREATE INDEX ix_test_period     ON technical_test (period_start, period_end);

CREATE TABLE attachment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technical_test_id  BIGINT       NOT NULL REFERENCES technical_test (id),
    original_filename  VARCHAR(255) NOT NULL,
    stored_filename    VARCHAR(100) NOT NULL,              -- server-generated, safe name
    content_type       VARCHAR(150) NOT NULL,
    file_size          BIGINT       NOT NULL DEFAULT 0,
    storage_location   VARCHAR(300) NOT NULL,              -- key inside the configured storage backend
    synthetic          BOOLEAN      NOT NULL DEFAULT FALSE, -- generated demo placeholder
    uploaded_by        VARCHAR(255) NOT NULL,
    uploaded_at        TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_attachment_size CHECK (file_size >= 0)
);
CREATE INDEX ix_attachment_test ON attachment (technical_test_id);

-- Used only when app.storage.type=database (persistent without a mounted volume)
CREATE TABLE attachment_content (
    storage_key   VARCHAR(300) PRIMARY KEY,                -- = attachment.storage_location
    data          BYTEA NOT NULL
);
