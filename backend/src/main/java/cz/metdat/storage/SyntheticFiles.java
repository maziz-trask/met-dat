package cz.metdat.storage;

import java.nio.charset.StandardCharsets;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.List;

/** Generates clearly labelled placeholder files for the demo attachments referenced by the workbook. */
public final class SyntheticFiles {
    private SyntheticFiles() {}

    public static byte[] forFile(String filename, String testNumber) {
        return filename.toLowerCase().endsWith(".csv") ? csv(filename, testNumber) : pdf(filename, testNumber);
    }

    static byte[] csv(String filename, String testNumber) {
        StringBuilder sb = new StringBuilder();
        sb.append("# SYNTHETIC DEMO FILE - generated by MET-DAT, not a real measurement\n");
        sb.append("# Placeholder for workbook reference: ").append(filename).append(" (").append(testNumber).append(")\n");
        sb.append("sample,value,unit\n");
        int seed = Math.abs((filename + testNumber).hashCode());
        for (int i = 1; i <= 5; i++) sb.append(i).append(',').append(10 + (seed * i) % 90).append(".0,demo\n");
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    static byte[] pdf(String filename, String testNumber) {
        List<String> lines = List.of("SYNTHETIC DEMO FILE", "", "This is NOT a real test report.",
            "Generated by the MET-DAT benchmark demo as a placeholder for the", "attachment referenced in the dummy dataset.", "",
            "Test: " + testNumber, "Referenced file: " + filename);
        StringBuilder content = new StringBuilder("BT /F1 16 Tf 72 760 Td 22 TL\n");
        for (String l : lines) content.append('(').append(esc(l)).append(") Tj T*\n");
        content.append("ET");
        List<String> objs = new ArrayList<>(List.of(
            "<< /Type /Catalog /Pages 2 0 R >>",
            "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
            "<< /Length " + content.length() + " >>\nstream\n" + content + "\nendstream",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"));
        StringBuilder out = new StringBuilder("%PDF-1.4\n");
        int[] offsets = new int[objs.size()];
        for (int i = 0; i < objs.size(); i++) {
            offsets[i] = out.length();
            out.append(i + 1).append(" 0 obj\n").append(objs.get(i)).append("\nendobj\n");
        }
        int xref = out.length();
        out.append("xref\n0 ").append(objs.size() + 1).append("\n0000000000 65535 f \n");
        for (int o : offsets) out.append(String.format("%010d 00000 n \n", o));
        out.append("trailer\n<< /Size ").append(objs.size() + 1).append(" /Root 1 0 R >>\nstartxref\n").append(xref).append("\n%%EOF\n");
        return out.toString().getBytes(StandardCharsets.ISO_8859_1);
    }

    private static String esc(String s) {
        String ascii = Normalizer.normalize(s, Normalizer.Form.NFD).replaceAll("[^\\x20-\\x7E]", "");
        return ascii.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)");
    }
}
